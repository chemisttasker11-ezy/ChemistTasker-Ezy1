#!/usr/bin/env python3
"""Generate/check the complete source cycle inventory without importing Django."""
import argparse
import json
from pathlib import Path
from module_import_graph import build_report, strongly_connected_components

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'docs/architecture/RUNTIME_CYCLE_LEDGER_20261029.json'

def inventory(parent):
    report = build_report()
    direct = {(r['from'], r['to']) for r in report['module_edges']}
    combined = direct | {(r['from'], r['to']) for r in report['delayed_edges']}
    def cyclic(edges):
        return {(a, b) for group in strongly_connected_components(edges) for a, b in edges if a in group and b in group}
    def entries(edges, kinds):
        return [{'from': a, 'to': b, 'sources': [dict(source, kind=kind)
                for kind, rows in [('module', report['module_edges']), ('delayed', report['delayed_edges'])]
                if kind in kinds for row in rows if (row['from'], row['to']) == (a, b)
                for source in row['sources']]} for a, b in sorted(cyclic(edges))]
    return dict(schema='chemisttasker-runtime-cycle-handover-v1', fixed_parent=parent,
        source='Generated by scripts/runtime_cycle_ledger.py from source; includes function-local imports.',
        module_edge_count=report['module_edge_count'], delayed_edge_count=report['delayed_edge_count'],
        direct_mutual_pairs=report['mutual_app_pairs'], direct_components=report['strongly_connected_components'],
        combined_components=strongly_connected_components(combined),
        direct_cyclic_edges=entries(direct, {'module'}), combined_cyclic_edges=entries(combined, {'module', 'delayed'}))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--parent', default='89a63155e99d67f64398ff670530b35a779cc607')
    options = parser.parse_args()
    result = inventory(options.parent)
    if options.check:
        assert json.loads(DESTINATION.read_text()) == json.loads(json.dumps(result)), 'Runtime ledger differs from source; regenerate it.'
    else:
        DESTINATION.write_text(json.dumps(result, indent=2) + '\n')
    print(f"Direct cyclic edges: {len(result['direct_cyclic_edges'])}; combined cyclic edges: {len(result['combined_cyclic_edges'])}")
