// Renders the web skill symbols (shared/SkillGlyph.tsx) to PNGs for Expo, so mobile shows the same artwork
// without a native SVG dependency. Run after changing the registry icons or SkillGlyph:
//   node frontend_web/scripts/render-mobile-skill-symbols.mjs
// Needs frontend_web/node_modules (rolldown, react-dom) and frontend_web/e2e/node_modules (@playwright/test).
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '..');
const root = path.resolve(web, '..');
const out = path.join(root, 'frontend_mobile', 'assets', 'skill-symbols');
const PT = 20; // chip/badge size in points, rendered at @3x so line weights match web
const requireWeb = createRequire(path.join(web, 'package.json'));
const requireE2E = createRequire(path.join(web, 'e2e', 'package.json'));

const work = path.join(tmpdir(), `ct-skill-symbols-${process.pid}`);
mkdirSync(work, { recursive: true });
const entry = path.join(work, 'entry.tsx');
writeFileSync(entry, `
import { renderToStaticMarkup } from 'react-dom/server';
import registry from '@chemisttasker/shared-core/skills_registry.json';
import { SkillSymbol } from ${JSON.stringify(path.join(web, 'shared', 'SkillGlyph.tsx'))};
export const codes = registry.skills.filter((s: any) => !s.logo).map((s: any) => s.code);
export const html = codes.map((code: string) => '<div id="' + code + '" style="display:inline-flex;line-height:0;margin:4px">' +
  renderToStaticMarkup(<SkillSymbol skill={code} size={${PT}} />) + '</div>').join('');
`);
const { build } = requireWeb('rolldown');
await build({
  input: entry, platform: 'node', logLevel: 'warn', transform: { jsx: { runtime: 'automatic' } },
  moduleTypes: { '.png': 'dataurl', '.svg': 'dataurl' },
  resolve: {
    alias: {
      '@chemisttasker/shared-core/skills_registry.json': path.join(root, 'shared-core', 'skills_registry.json'),
      '@chemisttasker/shared-core': path.join(root, 'shared-core', 'src', 'skills.ts'),
    },
    modules: [path.join(web, 'node_modules'), 'node_modules'],
  },
  output: { file: path.join(work, 'entry.mjs'), format: 'esm' },
});
const { codes, html } = await import(pathToFileURL(path.join(work, 'entry.mjs')).href);

const { chromium } = requireE2E('@playwright/test');
const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 3 });
await page.setContent(`<!doctype html><body style="margin:0;background:transparent">${html}</body>`);
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const code of codes) {
  await page.locator(`#${code} > span`).screenshot({ path: path.join(out, `${code}.png`), omitBackground: true });
}
await browser.close();
rmSync(work, { recursive: true, force: true });

writeFileSync(path.join(out, 'index.ts'), `// Generated by frontend_web/scripts/render-mobile-skill-symbols.mjs from shared/SkillGlyph.tsx. Do not edit.
export const SKILL_SYMBOLS: Record<string, number> = {
${codes.map(code => `  ${code}: require('./${code}.png'),`).join('\n')}
};
`);
console.log(`Rendered ${codes.length} skill symbols to ${path.relative(root, out)}`);
JSON.parse(readFileSync(path.join(root, 'shared-core', 'skills_registry.json'), 'utf8')); // registry stays valid JSON
