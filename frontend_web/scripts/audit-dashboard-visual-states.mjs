import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = p => readFileSync(new URL(p, import.meta.url), "utf8");
const state = read("../src/components/dashboard/DashboardContentState.tsx");
const shifts = read("../src/pages/dashboard/sidebar/ShiftsBoard/components/ShiftList.tsx");
const talent = read("../src/pages/dashboard/sidebar/TalentBoard/index.tsx");
const finance = read("../src/pages/finance/FinanceWorkspace.tsx");
for (const kind of ['loading','empty','error']) assert.ok(state.includes('"' + kind + '"'), "Missing visual state "+kind);
assert.match(state,/Mui|<Paper/);
assert.match(state,/aria-busy/);
assert.match(state,/role=\{isError \? "alert" : "status"\}/);
assert.match(shifts,/DashboardContentState kind="loading"/);
assert.match(shifts,/kind="empty"/);
assert.match(talent,/kind="error"/);
assert.match(talent,/No published talent yet/);
assert.match(talent,/No candidates match your filters/);
assert.match(talent,/Publish your availability/);
assert.match(finance,/Loading finance records/);
assert.match(finance,/No matching received invoices/);
assert.match(finance,/receivedMode \? ownerTools : workerTools/);
assert.match(finance,/actionLabel="Reset filters"/);
for(const src of [state,shifts,talent,finance])assert.ok(!src.includes('figma.com/api/mcp/asset'),"Do not use temporary Figma assets");
console.log("PASS: shared React loading/empty/error visual-state contracts");
